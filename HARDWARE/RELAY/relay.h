/*
==================================================
    继电器驱动头文件 (relay.h)

    功能：
    定义继电器控制宏和继电器初始化函数声明。

    硬件连接：
    - RELAY : PC0 (推挽输出)

    说明：
    继电器为高电平吸合(导通)，低电平断开。
    初始化时输出低电平使继电器处于断开状态。
==================================================
*/
#ifndef __RELAY_H
#define __RELAY_H
#include "sys.h"

/* 继电器控制宏，通过位带操作直接控制GPIO输出 */
#define RELAY PCout(0)  /* 继电器对应PC0引脚输出，1=吸合(导通)，0=断开 */

/*
    继电器初始化函数
    配置PC0为推挽输出，默认输出低电平(继电器断开)
    参数：无
    返回值：无
*/
void relay_init(void);

#endif


