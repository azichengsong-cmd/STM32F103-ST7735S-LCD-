/*
==================================================
    LED驱动头文件 (led.h)

    功能：
    定义LED控制宏和LED初始化函数声明。

    硬件连接：
    - LED1 : PA6 (推挽输出)
    - LED2 : PA7 (推挽输出)

    说明：
    LED为低电平点亮（共阳接法），
    初始化时输出高电平使LED熄灭。
==================================================
*/
#ifndef __LED_H
#define __LED_H
#include "sys.h"

/* LED控制宏，通过位带操作直接控制GPIO输出 */
#define LED1 PAout(6)  /* LED1对应PA6引脚输出，0=点亮，1=熄灭 */
#define LED2 PAout(7)  /* LED2对应PA7引脚输出，0=点亮，1=熄灭 */

/*
    LED初始化函数
    配置PA6、PA7为推挽输出，默认输出高电平(LED熄灭)
    参数：无
    返回值：无
*/
void led_init(void);

#endif


