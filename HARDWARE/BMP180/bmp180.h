#ifndef __BMP180_H
#define __BMP180_H

#include "sys.h"


/*================================================
 * BMP180 IIC设备地址
 *
 * BMP180的7位IIC地址为0x77，
 * 左移1位后为0xEE（写）和0xEF（读）。
 *================================================*/
#define BMP180_ADDR        0x77


/*================================================
 * BMP180寄存器地址定义
 *================================================*/

#define BMP180_CHIP_ID_REG 0xD0   /* 芯片ID寄存器，读取值应为0x55 */

#define BMP180_CONTROL     0xF4   /* 控制/测量命令寄存器 */
#define BMP180_RESULT      0xF6   /* 测量结果数据寄存器（温度/压力共用） */


/*================================================
 * BMP180测量命令
 *
 * 写入BMP180_CONTROL寄存器的命令值
 *================================================*/

#define BMP180_TEMP_CMD    0x2E   /* 温度测量命令 */

#define BMP180_PRESS_CMD   0x34   /* 压力测量命令（OSS=0，最低精度） */



/*================================================
 * BMP180校准参数与数据结构体
 *
 * 存储从芯片读取的校准参数、原始测量数据、
 * 中间计算变量以及最终计算结果。
 *================================================*/
typedef struct
{

    /* 校准参数（出厂校准，每个芯片不同） */

    short AC1;            /* AC1：压力补偿参数1（有符号） */
    short AC2;            /* AC2：压力补偿参数2（有符号） */
    short AC3;            /* AC3：压力补偿参数3（有符号） */


    unsigned short AC4;   /* AC4：压力补偿参数4（无符号） */
    unsigned short AC5;   /* AC5：温度补偿参数1（无符号） */
    unsigned short AC6;   /* AC6：温度补偿参数2（无符号） */


    short B1;             /* B1：压力补偿参数（有符号） */
    short B2;             /* B2：压力补偿参数（有符号） */


    short MB;             /* MB：保留参数 */
    short MC;             /* MC：温度补偿参数（有符号） */
    short MD;             /* MD：温度补偿参数（有符号） */



    /* 原始测量数据 */

    long UT;      /* 温度原始数据（未补偿） */

    long UP;      /* 压力原始数据（未补偿） */



    /* 中间计算变量 */

    long B5;      /* B5：温度计算的中间变量，压力计算也需要 */



    /* 最终计算结果 */

    long temperature;   /* 真实温度，单位0.1℃ */

    long pressure;      /* 真实气压，单位Pa */

    long altitude;      /* 海拔高度，单位m */


}BMP180_TypeDef;



/* 全局BMP180数据结构体，外部引用 */
extern BMP180_TypeDef bmp180;



/*================================================
 * BMP180函数声明
 *================================================*/

void BMP180_Init(void);             /* 初始化BMP180，读取ID和校准参数 */


u8 BMP180_ReadID(void);             /* 读取芯片ID */


short BMP180_Read16(u8 reg);        /* 读取16位寄存器值 */



long BMP180_ReadTemperature(void);  /* 读取温度（0.1℃） */



long BMP180_ReadPressure(void);     /* 读取气压（Pa） */



long BMP180_ReadAltitude(void);     /* 计算海拔（m） */



#endif



