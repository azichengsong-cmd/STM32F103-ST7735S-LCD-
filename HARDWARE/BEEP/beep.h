/*
==================================================
    蜂鸣器驱动头文件 (beep.h)

    功能：
    定义蜂鸣器控制宏和蜂鸣器初始化函数声明。

    硬件连接：
    - BEEP : PC9 (推挽输出)

    说明：
    蜂鸣器为高电平鸣响，低电平静音。
    初始化时输出低电平使蜂鸣器静音。
==================================================
*/
#ifndef __BEEP_H
#define __BEEP_H
#include "sys.h"

/* 蜂鸣器控制宏，通过位带操作直接控制GPIO输出 */
#define BEEP PCout(9)  /* 蜂鸣器对应PC9引脚输出，1=鸣响，0=静音 */

/*
    蜂鸣器初始化函数
    配置PC9为推挽输出，默认输出低电平(蜂鸣器静音)
    参数：无
    返回值：无
*/
void beep_init(void);


#endif



