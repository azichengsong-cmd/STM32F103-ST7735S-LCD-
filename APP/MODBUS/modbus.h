#ifndef __MODBUS_H
#define __MODBUS_H

#include "sys.h"

/*================================================
 * Modbus 从机地址
 *
 * 本设备作为Modbus RTU从机，
 * 地址为1，主机通过此地址寻址。
 *================================================*/
#define MODBUS_SLAVE_ID       1

/*================================================
 * 保持寄存器数量
 *
 * 当前共10个保持寄存器，
 * 寄存器0~2分别存储温度、气压、海拔，
 * 寄存器3~9为预留。
 *================================================*/
#define MODBUS_REG_NUM        10

/*================================================
 * Modbus 请求帧长度
 *
 * 01 03 00 00 00 0A C5 CD
 *
 * 共8字节（从机地址+功能码+起始地址+数量+CRC）
 *================================================*/
#define MODBUS_REQUEST_LEN    8

/*================================================
 * Modbus 最大响应长度
 *
 * 01          从机地址
 * 03          功能码
 * 14          字节数（20字节 = 10个寄存器 × 2）
 * 20字节数据  10个寄存器的值
 * CRC 2字节   校验值
 *
 * 共24字节
 *================================================*/
#define MODBUS_RESPONSE_LEN   24


/*================================================
 * Modbus 初始化
 *
 * 初始化保持寄存器为测试数据，
 * 打印从机配置信息。
 *================================================*/
void Modbus_Init(void);


/*================================================
 * Modbus CRC16校验
 *
 * 参数：buf - 数据缓冲区
 *       len - 数据长度
 * 返回：CRC16校验值
 *================================================*/
u16 Modbus_CRC16(u8 *buf, u16 len);


/*================================================
 * Modbus 非阻塞处理函数
 *
 * 有数据：
 *     接收并处理
 *
 * 没有数据：
 *     立即返回
 *
 * 不会阻塞主循环
 *================================================*/
void Modbus_Process(void);


/*================================================
 * 更新Modbus保持寄存器
 *
 * 将sensor中的数据
 * 更新到Modbus寄存器
 *================================================*/
void Modbus_UpdateRegisters(void);


/*================================================
 * 保持寄存器
 *
 * 外部引用声明，其他文件可通过此数组
 * 直接访问Modbus保持寄存器的值。
 * 寄存器0=温度, 1=气压, 2=海拔, 3~9=预留。
 *================================================*/
extern u16 Modbus_HoldingReg[MODBUS_REG_NUM];


#endif


