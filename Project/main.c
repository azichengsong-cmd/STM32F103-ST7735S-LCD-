/*
==================================================
    主程序文件 (main.c)

    功能：
    STM32嵌入式系统主程序，集成BMP180传感器、LCD显示、
    OneNET MQTT云平台上传、Modbus RS485通信、报警、
    Flash历史数据存储、天气获取等功能。

    系统架构：
    - TIM2定时器：10ms中断，产生500ms传感器更新和30s MQTT上传标志
    - 主循环：轮询处理Modbus、传感器更新、UI显示、按键、MQTT上传、Flash保存

    定时器时序说明：
    - TIM2中断周期：10ms (72MHz/7200/100 = 100Hz)
    - 传感器数据更新：每500ms (Sensor_Count计数到50，50×10ms=500ms)
    - MQTT数据上传：每30s (MQTT_Count计数到3000，3000×10ms=30000ms=30s)
    - Flash历史数据保存：每30s (与MQTT上传同步执行)

    中断优先级分配(NVIC_PriorityGroup_2)：
    - USART2(抢占0)：Air780E通信，最高优先级
    - TIM2(抢占2)：系统节拍
    - USART1(抢占3)：调试串口，最低优先级
==================================================
*/
